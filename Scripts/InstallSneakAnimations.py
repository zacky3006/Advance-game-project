"""Run with -EnablePlugins=MoverExamples -ExecutePythonScript=<this file>.
Copies Epic's bundled Manny crouch clips; runtime does not require Mover.
Existing retargeters adapt these clips to Ninja and John. Original ABPs are
backed up under Saved/SneakAnimationBackup before the graph is updated.
"""
import unreal as u
from pathlib import Path
import shutil

try:
    lib = u.SneakAnimationEditorLibrary
    assets = u.EditorAssetLibrary
    tools = u.AssetToolsHelpers.get_asset_tools()
    root = '/Game/Characters/Mannequins/Anims/Sneak'
    names = ['Idle', 'Walk_Fwd', 'Walk_Bwd', 'Walk_Left', 'Walk_Right']
    skeleton = u.load_asset('/Game/Characters/Mannequins/Meshes/SK_Mannequin')
    clips = []
    for name in names:
        target = root + '/MM_Unarmed_Crouch_' + name
        clip = u.load_asset(target) if assets.does_asset_exist(target) else assets.duplicate_asset(
            '/MoverExamples/Characters/Mannequins/Animations/Manny/MM_Unarmed_Crouch_' + name, target)
        assert clip, target
        lib.set_matching_skeleton(clip, skeleton)
        assert clip.get_editor_property('skeleton') == skeleton, target
        clip.set_editor_property('enable_root_motion', False)
        clip.set_editor_property('force_root_lock', not clip.get_name().endswith('_Idle'))
        assets.save_loaded_asset(clip, only_if_is_dirty=False)
        clips.append(clip)

    groups = [('Mannequins', '/Game/Characters/Mannequins/Anims/Unarmed/ABP_Unarmed', root, clips)]
    for character, mesh in [('Ninja', 'Ch24_nonPBR'), ('John', 'Ch33_nonPBR')]:
        folder = '/Game/Characters/' + character
        target_folder = folder + '/Sneak'
        character_clips = []
        if not all(assets.does_asset_exist(target_folder + '/' + clip.get_name()) for clip in clips):
            results = u.IKRetargetBatchOperation.duplicate_and_retarget(
                [assets.find_asset_data(clip.get_path_name()) for clip in clips],
                u.load_asset('/Game/Characters/Mannequins/Meshes/SKM_Quinn_Simple'),
                u.load_asset(folder + '/' + mesh), u.load_asset(folder + '/RTG_AutoGenerated'),
                '', '', character + '_', '', False, False)
            assert len(results) == 5, 'retarget failed: ' + character
            for result in results:
                clip = result.get_asset()
                original_name = clip.get_name().removeprefix(character + '_')
                destination = target_folder + '/' + original_name
                assert assets.rename_asset(clip.get_path_name(), destination)
        for source in clips:
            clip = u.load_asset(target_folder + '/' + source.get_name())
            assert clip
            clip.set_editor_property('enable_root_motion', False)
            clip.set_editor_property('force_root_lock', not clip.get_name().endswith('_Idle'))
            assets.save_loaded_asset(clip)
            character_clips.append(clip)
        groups.append((character, folder + '/ABP_' + character, target_folder, character_clips))

    backup = Path(u.Paths.project_saved_dir()) / 'SneakAnimationBackup'
    backup.mkdir(exist_ok=True)
    for character, bp_path, folder, group_clips in groups:
        blueprint = u.load_asset(bp_path)
        file = Path(u.Paths.project_content_dir()) / (bp_path.removeprefix('/Game/') + '.uasset')
        backup_file = backup / (character + '_' + file.name)
        if not backup_file.exists(): shutil.copy2(file, backup_file)
        blend_path = folder + '/BS_Crouch'
        if assets.does_asset_exist(blend_path):
            blend = u.load_asset(blend_path)
        else:
            factory = u.BlendSpaceFactoryNew()
            factory.set_editor_property('target_skeleton', blueprint.get_editor_property('target_skeleton'))
            blend = tools.create_asset('BS_Crouch', folder, u.BlendSpace, factory)
            assert lib.configure_sneak_blend_space(blend, group_clips), character
            assets.save_loaded_asset(blend)
        assert lib.install_sneak_graph(blueprint, blend), 'graph failed: ' + character
        assert assets.save_loaded_asset(blueprint), bp_path
        u.log('SNEAK_INSTALL PASS ' + character)

    # No runtime references to the experimental plugin should remain.
    registry = u.AssetRegistryHelpers.get_asset_registry()
    registry.scan_modified_asset_files([
        str(Path(u.Paths.project_content_dir()) / (asset_path.split('.')[0].removeprefix('/Game/') + '.uasset'))
        for _, _, folder, _ in groups
        for asset_path in assets.list_assets(folder, recursive=True, include_folder=False)])
    options = u.AssetRegistryDependencyOptions(True, True, True, True, True)
    for _, bp_path, folder, _ in groups:
        for asset_path in assets.list_assets(folder, recursive=True, include_folder=False):
            for dep in registry.get_dependencies(asset_path.split('.')[0], options):
                assert not str(dep).startswith('/MoverExamples/'), (asset_path, str(dep))
    u.log('SNEAK_INSTALL ALL PASSED: crouch idle/walk; plugin independent')
except Exception:
    u.log_error('SNEAK_INSTALL FAILED')
    import traceback
    u.log_error(traceback.format_exc())
finally:
    u.SystemLibrary.quit_editor()
